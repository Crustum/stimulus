<?php
declare(strict_types=1);

namespace Crustum\Stimulus\Worker;

use Cake\Http\CallbackStream;
use Closure;
use Crustum\Stimulus\Http\StimulusResponse;
use Generator;
use Psr\Http\Message\ResponseInterface;
use ReflectionFunction;
use ReflectionNamedType;

/**
 * Marshals worker responses for the server bridge clients.
 *
 * Requests and responses are natively PSR-7. Request marshalling lives in the RoadRunner
 * and FrankenPHP bridge clients, which build `Cake\Http\ServerRequest`
 * instances directly; the worker loop only keeps wrapping the handled
 * response plus its output buffer into the response envelope.
 *
 * Callback-streamed bodies (`CallbackStream`, the body behind
 * `AbstractStreamResponse` server streaming) additionally resolve into an
 * envelope chunk producer when their callback declares a generator or string
 * return. Echo-style callbacks stay buffered.
 */
trait MarshalsPsr7RequestsAndResponsesTrait
{
    /**
     * Wraps the handled response and its output buffer into the worker envelope.
     *
     * Responses with a callback-streamed body keep a working body: the
     * callback is detached for inspection and reattached, so non-streaming
     * consumers still read the stream.
     *
     * @param \Psr\Http\Message\ResponseInterface $response Response generated by the application.
     * @param string|null $outputBuffer Output buffered while handling the request.
     * @return \Crustum\Stimulus\Http\StimulusResponse Worker response envelope.
     */
    protected function toStimulusResponse(ResponseInterface $response, ?string $outputBuffer = null): StimulusResponse
    {
        $body = $response->getBody();

        if (!$body instanceof CallbackStream) {
            return new StimulusResponse($response, $outputBuffer);
        }

        $callback = $body->detach();

        if ($callback !== null) {
            $response = $response->withBody(new CallbackStream($callback));
        }

        return new StimulusResponse($response, $outputBuffer, $this->streamingProducer($callback));
    }

    /**
     * Resolves a body-chunk producer from the given stream callback.
     *
     * Only callbacks declaring a generator or string return produce chunks; anything else (including a
     * detached/absent callback) stays buffered. Chunks must be strings or
     * stringable; anything else fails loudly instead of corrupting the stream.
     *
     * @param callable|null $callback Detached body callback, or null when the stream carried none.
     * @return (\Closure():\Generator)|null Chunk producer, or null for buffered responses.
     */
    protected function streamingProducer(mixed $callback): ?Closure
    {
        if (!$callback instanceof Closure && !is_string($callback)) {
            return null;
        }

        $reflection = new ReflectionFunction($callback);

        if (!$reflection->hasReturnType()) {
            return null;
        }

        $returnType = $reflection->getReturnType();

        if (!$returnType instanceof ReflectionNamedType) {
            return null;
        }

        if (!in_array($returnType->getName(), [Generator::class, 'string'], true)) {
            return null;
        }

        return static function () use ($callback): Generator {
            $result = $callback();

            if (!$result instanceof Generator) {
                yield (string)$result;

                return;
            }

            foreach ($result as $chunk) {
                yield is_string($chunk) ? $chunk : (string)$chunk;
            }
        };
    }
}
