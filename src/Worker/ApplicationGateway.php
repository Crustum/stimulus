<?php
declare(strict_types=1);

namespace Crustum\Stimulus\Worker;

use Cake\Http\BaseApplication;
use Cake\Http\MiddlewareQueue;
use Cake\Http\Runner;
use Cake\Http\Server;
use Cake\Http\ServerRequest;
use Cake\Routing\Router;
use Crustum\Stimulus\Event\RequestHandledEvent;
use Crustum\Stimulus\Event\RequestReceivedEvent;
use Crustum\Stimulus\Event\RequestTerminatedEvent;
use Crustum\Stimulus\Http\CurrentApplication;
use Crustum\Stimulus\StimulusManager;
use Psr\Http\Message\ResponseInterface;

/**
 * Dispatches requests through the current sandbox application.
 *
 * The middleware pipeline handles requests, because the application
 * `handle` reaches the controller factory directly with no middleware queue, no
 * `Server.buildMiddleware` event, and no runner. Every operation dispatches
 * through the current sandbox handle, never the stale boot-time instance,
 * which the sandbox-swap worker test proves. The request is re-read from
 * the received event after dispatch so listeners replacing the request stay
 * coherent with the handler input.
 */
class ApplicationGateway
{
    use DispatchesEventsTrait;

    /**
     * Manager holding the in-worker routes.
     *
     * @var \Crustum\Stimulus\StimulusManager
     */
    protected StimulusManager $manager;

    /**
     * Creates a new application gateway.
     *
     * @param \Cake\Http\BaseApplication $app Base application instance.
     * @param \Cake\Http\BaseApplication $sandbox Sandbox application instance handling the request.
     * @param \Crustum\Stimulus\StimulusManager|null $manager Manager holding the in-worker routes, or null for a fresh manager.
     */
    public function __construct(
        protected BaseApplication $app,
        protected BaseApplication $sandbox,
        ?StimulusManager $manager = null,
    ) {
        $this->manager = $manager ?? new StimulusManager();
    }

    /**
     * Handles an incoming request through the current sandbox.
     *
     * In-worker manager routes answer directly without a handled event,
     * while the middleware pipeline dispatches the handled event around its
     * response. Host routing resolves inside the routing middleware, so no
     * gateway route-table handling is needed.
     *
     * @param \Cake\Http\ServerRequest $request Incoming request.
     * @return \Psr\Http\Message\ResponseInterface Response generated by the sandbox.
     */
    public function handle(ServerRequest $request): ResponseInterface
    {
        $event = new RequestReceivedEvent($this->app, $this->sandbox, $request);

        $this->dispatchEvent($this->sandbox, $event);

        $request = $event->getRequest();

        $uri = '/' . ltrim($request->getPath(), '/');

        if ($this->manager->hasRouteFor($request->getMethod(), $uri)) {
            return $this->manager->invokeRoute($request, $request->getMethod(), $uri);
        }

        $response = $this->runMiddlewareStack($request);

        $this->dispatchEvent($this->sandbox, new RequestHandledEvent($this->sandbox, $request, $response));

        return $response;
    }

    /**
     * Runs the given request through the sandbox middleware pipeline.
     *
     * Builds a fresh queue from the sandbox per operation, exactly like the
     * framework server run, including the container-aware queue and the
     * plugin middleware pass. The process-global route table resets first:
     * the routing middleware reconnects application and plugin routes on
     * every run, so without the reset named routes collide from the second
     * operation on while unnamed ones accumulate silently. The
     * `Server.buildMiddleware` event fires
     * through a server wrapping the sandbox so host applications and plugins
     * hook workers exactly like short-lived requests; the wrapper owns a
     * fresh event manager, which still reaches globally registered
     * listeners. Boot stays once per worker: unlike the framework server
     * run, this never re-bootstraps the application. The session closes
     * after the run so worker session state never leaks across operations.
     *
     * @param \Cake\Http\ServerRequest $request Incoming request.
     * @return \Psr\Http\Message\ResponseInterface Response generated by the pipeline.
     */
    protected function runMiddlewareStack(ServerRequest $request): ResponseInterface
    {
        Router::reload();

        $middleware = $this->sandbox->middleware(new MiddlewareQueue([], $this->sandbox->getContainer()));
        $middleware = $this->sandbox->pluginMiddleware($middleware);

        (new Server($this->sandbox))->dispatchEvent('Server.buildMiddleware', ['middleware' => $middleware]);

        $response = (new Runner())->run($middleware, $request, $this->sandbox);

        $request->getSession()->close();

        return $response;
    }

    /**
     * Shuts down the sandbox application after a request.
     *
     * Per-operation teardown is event-driven through the terminated event
     * instead of a kernel call. Controllers are per-request instances created
     * inside `handle`, so nothing persists to flush. Resets the current-application seam so a
     * stale request never leaks into the next operation.
     *
     * @param \Cake\Http\ServerRequest $request Request that was handled.
     * @param \Psr\Http\Message\ResponseInterface $response Response generated for the request.
     * @return void
     */
    public function terminate(ServerRequest $request, ResponseInterface $response): void
    {
        $this->dispatchEvent(
            $this->sandbox,
            new RequestTerminatedEvent($this->app, $this->sandbox, $request, $response),
        );

        CurrentApplication::reset();
    }
}
