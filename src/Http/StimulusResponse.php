<?php
declare(strict_types=1);

namespace Crustum\Stimulus\Http;

use Closure;
use Psr\Http\Message\ResponseInterface;

/**
 * Worker response envelope handed back to the server client.
 *
 * Carries the PSR-7 response, any output buffered while the application
 * handled the request, and an optional body-chunk producer. The producer is
 * set when the application answered with a callback-streamed body whose
 * callback declares a generator or string return, so bridge clients can
 * stream it instead of sending one buffered response.
 */
class StimulusResponse
{
    /**
     * Creates a new worker response envelope.
     *
     * @param \Psr\Http\Message\ResponseInterface $response Response generated by the application.
     * @param string|null $outputBuffer Output buffered while handling the request.
     * @param (\Closure():\Generator)|null $streamer Producer of string body chunks for streamed responses, or null for buffered responses.
     */
    public function __construct(
        public ResponseInterface $response,
        public ?string $outputBuffer = null,
        public ?Closure $streamer = null,
    ) {
    }
}
